Listen politely and ask for 24 hours to reflect. Before changing your mind, ask whether the non-salary reasons you started job hunting (workload, growth ceiling, commute, or management style) will actually change over the next six months.

### What If My Employer Rejects My Two Weeks Notice Period?
Some roles—especially in sales, finance, or security-sensitive engineering—choose to revoke system access on the same day you resign while paying you through part or all of your notice period (`TODO: verify` local final pay rules for early notice release). Keep a personal backup copy of your sent letter and date-stamped HR reply.

### Can I Withdraw My Resignation Later?
You may submit a written request asking to rescind your notice as soon as possible, though employers are generally under no obligation to reinstate an accepted resignation. Think carefully before initiating a formal exit.

