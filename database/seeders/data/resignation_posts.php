## Resignation Letter Dos and Don’ts

**Do:**
- Keep the body under 150 to 200 words (three crisp paragraphs is the sweet spot).
- Stay professional, factual, and forward-looking even if workplace frustration prompted your move.
- Double-check dates against holidays or weekend schedules so HR and payroll records align.
- Pick wording aligned to your scenario—whether leaving for a [new job](/resignation-letter/new-job), [personal reasons](/resignation-letter/personal-reasons), [relocation](/resignation-letter/relocation), or [short notice](/resignation-letter/short-notice).

**Don’t:**
- Do not vent about managers, colleagues, pay disputes, or company politics in writing—letters stay on file permanently.
- Do not share private medical records, household specifics, or compensation terms from your next employer.
- Do not announce your departure in group chats before telling your manager directly.

